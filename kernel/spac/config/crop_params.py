RICE_YIELD_MOISTURE = 0.145


def yield_moisture(crop: str) -> float:
    """报告产量的湿基含水率；玉米保持原有干重口径，避免改变未请求的率定。"""
    return RICE_YIELD_MOISTURE if crop.lower() in ("rice", "paddy", "水稻") else 0.0

