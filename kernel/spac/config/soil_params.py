        # 该层非限制层(犁底层 4 mm/d 才是通量控制层),取值仅影响泡田/降雨的
        # 瞬时入渗速率,不影响全季渗漏总量
        # penetrability: 内核要求百分数(0-100), 100=完全可穿透
